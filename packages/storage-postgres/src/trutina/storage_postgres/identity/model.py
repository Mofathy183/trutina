"""SQLAlchemy model for the `users` table.

Maps a person who can authenticate onto a single table. Contains no
business rules: email normalization belongs to `trutina-authentication`'s
`User` model, which hands this table an already-normalized address.

`email` is the one and only identity column. Because it is stored
normalized (trimmed and case-folded), a plain unique constraint is
enough to enforce case-insensitive uniqueness. There is deliberately no
separate lookup-key column.

`password_hash` stays NOT NULL until an OAuth login exists. `id` is
supplied by the application, not generated by the database, because it
is the subject identifier carried by tokens and audit records.
"""

from uuid import UUID

from sqlalchemy import Boolean, Text, Uuid, true
from sqlalchemy.orm import Mapped, mapped_column
from trutina.storage_postgres.shared import Base, TimestampedMixin


class UserModel(TimestampedMixin, Base):
    """Persistence row for one user.

    Attributes:
        id: Application-supplied UUID primary key.
        email: Normalized login identifier. Unique.
        password_hash: Output of the password hasher.
        is_active: Whether the user may authenticate and write.
            Deactivation replaces deletion; users are never removed.
    """

    __tablename__ = "users"

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True)
    email: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)
    is_active: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=true()
    )
